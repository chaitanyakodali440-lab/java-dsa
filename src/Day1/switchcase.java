package Day1;

public class switchcase {
    public static void main(String[] args){
        int choice = 2;
        switch(choice)
        {
            case 1:
                System.out.println("your choice is perfect"+1);
                break;
            case 2:
                System.out.println(" Your choice is perfect"+2);
                break;
            default:
                System.out.println("None of them are perfect");
        }
    }
}
